"""Progress V2 PR3 — Axis Insight in a real browser.

Hermetic Chromium (tests/ux4_gate_support.py): the real template + static
bundle of this commit, served by the Flask test client. Both Progress reads
the insight depends on are fulfilled with payloads generated by the SERVER's
own projection functions for synthetic canonical reports, so each state below
is exactly what production would publish for such a user:

  needs attention (consistency gaps) · on track (ready to progress) ·
  building baseline · no standout signal (holding steady) · endpoint failure

For every state × 320/390/1024/1366 × EN/TR it proves: no horizontal
overflow, the action block and the CTA never overlap, the CTA is visible and
tappable (≥ 44px), the surface reads interpretation → evidence → action → CTA
top-to-bottom, the rendered sentences never repeat Current State or Trends,
and exactly the page's existing reads happen (no new request).

Set AXIS_QA_SHOTS=<dir> to also save one screenshot per cell.

    python -m pytest tests/test_progress_axis_insight_browser.py -v
"""
import json
import os
from datetime import date

import pytest

from ux4_gate_support import gate, ready  # noqa: F401  (fixture re-export)

from app.services.progress_insights import (
    ProgressInsights,
    progress_insights_payload,
    select_insight,
    select_next_move,
    select_watch,
    select_working,
)
from app.services.progress_summary import (
    TRAJECTORY_BY_SIGNAL,
    build_window,
    summarize_consistency,
    summarize_performance,
)
from app.services.training_history.models import WeeklyVolume
from app.services.training_planning import derive_adaptive_plan
from app.services.training_progression import ProgressionReport
from app.services.training_progression.analysis import (
    MIN_DELOAD_WEEKS,
    MIN_PLATEAU_WEEKS,
)

pytestmark = pytest.mark.filterwarnings("ignore")

SUMMARY = "/api/progress/summary"
AXIS = "/api/progress/axis-insights"
WIDTHS = (320, 390, 1024, 1366)

STATES = {
    "needs_attention": dict(signal="build_consistency", sessions=(2, 0, 3, 0),
                            consistency="inconsistent"),
    "on_track": dict(signal="progressing", volume="up", strength="up"),
    "baseline": dict(signal="insufficient_data", sessions=(1, 0, 0, 0),
                     consistency="insufficient_data"),
    "no_standout": dict(signal="keep_pushing"),
}


def _report(signal, *, volume="flat", strength="flat", sessions=(3, 3, 3, 3),
            consistency="consistent"):
    weekly = [WeeklyVolume(week_start=date(2026, 8, 28), session_count=n,
                           total_volume=1100.0 * n + 50 * i)
              for i, n in enumerate(sessions)]
    return ProgressionReport(
        weeks=4, has_data=signal != "insufficient_data", next_signal=signal,
        load_consistency=consistency, volume_trend=volume,
        strength_trend=strength, weekly_volume=weekly)


def _payloads(state):
    report = _report(**STATES[state])
    plan = derive_adaptive_plan(report)
    performance = summarize_performance(report)
    consistency = summarize_consistency(report)
    axis = progress_insights_payload(ProgressInsights(
        window=build_window(date(2026, 9, 24), 4),
        working=select_working(performance, consistency),
        watch=select_watch(plan, consistency),
        next_move=select_next_move(plan),
        insight=select_insight(plan, performance, consistency,
                               deload_weeks=MIN_DELOAD_WEEKS,
                               plateau_weeks=MIN_PLATEAU_WEEKS),
    ))
    summary = {
        "contract_version": 1,
        "window": {"weeks": 4, "start": "2026-08-28", "end": "2026-09-24",
                   "timezone": "Europe/Istanbul"},
        "trajectory": {"state": TRAJECTORY_BY_SIGNAL[report.next_signal],
                       "reason": report.next_signal},
        "body": {"status": "available", "current_weight_kg": 78.4,
                 "weight_delta_kg": -0.6, "target_weight_kg": 75.0,
                 "distance_to_target_kg": 3.4,
                 "weight_series": [{"day": "2026-09-03", "weight_kg": 79.4},
                                   {"day": "2026-09-10", "weight_kg": 79.0},
                                   {"day": "2026-09-17", "weight_kg": 78.4}]},
        "performance": {"state": performance.state,
                        "volume_trend": performance.volume_trend,
                        "strength_trend": performance.strength_trend,
                        "next_signal": report.next_signal},
        "consistency": {"state": consistency.state,
                        "active_weeks": consistency.active_weeks,
                        "analyzed_weeks": consistency.analyzed_weeks,
                        "sessions": consistency.sessions},
        "weekly": [{"start": "2026-08-28", "sessions": w.session_count,
                    "active": w.session_count > 0,
                    "volume_kg": w.total_volume} for w in report.weekly_volume],
    }
    return summary, axis


PROBE = r"""
() => {
  const q = s => document.querySelector(s);
  const card = q('#ax-card');
  const box = el => { const r = el.getBoundingClientRect();
                      return {top: r.top, bottom: r.bottom, left: r.left,
                              right: r.right, width: r.width, height: r.height}; };
  const shown = el => el && !el.hidden && el.getBoundingClientRect().height > 0;
  const texts = sel => [...document.querySelectorAll(sel)]
      .filter(el => !el.hidden && el.checkVisibility())
      .map(el => el.textContent.trim()).filter(Boolean);
  const action = q('#ax-action'), cta = q('#ax-review'), interp = q('#ax-interpretation');
  const ev = q('#ax-evidence');
  return {
    overflow: document.documentElement.scrollWidth > document.documentElement.clientWidth,
    status: card.getAttribute('data-status'),
    busy: card.hasAttribute('aria-busy'),
    interp: interp.textContent.trim(),
    meaning: shown(q('#ax-meaning')) ? q('#ax-meaning').textContent.trim() : null,
    evidence: shown(ev) ? [...ev.children].map(li => li.textContent.trim()) : [],
    hiddenTakesSpace: [...card.querySelectorAll('[hidden]')]
        .some(el => getComputedStyle(el).display !== 'none'),
    action: shown(action) ? q('#ax-action-text').textContent.trim() : null,
    detail: shown(q('#ax-action-detail')) ? q('#ax-action-detail').textContent.trim() : null,
    boxes: {interp: box(interp), evidence: shown(ev) ? box(ev) : null,
            action: shown(action) ? box(action) : null, cta: box(cta), card: box(card)},
    cardOverflow: card.scrollWidth > card.clientWidth,
    ctaText: cta.textContent.trim(),
    ctaHref: cta.getAttribute('href'),
    current: texts('#progress-current-state p, #progress-current-state li'),
    trends: texts('#progress-trends p, #progress-trends li, #progress-trends span'),
  };
}
"""


def _overlap(a, b):
    return not (a["right"] <= b["left"] or b["right"] <= a["left"]
                or a["bottom"] <= b["top"] or b["bottom"] <= a["top"])


@pytest.mark.parametrize("locale", ["en", "tr"])
@pytest.mark.parametrize("state", sorted(STATES) + ["failure"])
def test_axis_insight_renders_one_coherent_surface(
        app, gate, make_user, login, state, locale):  # noqa: F811
    user = make_user("axbr_%s_%s" % (state, locale))
    ready(app, user.id, language=locale)
    login("axbr_%s_%s" % (state, locale))

    summary, axis = _payloads("no_standout" if state == "failure" else state)
    gate.overrides[SUMMARY] = (200, json.dumps(summary))
    gate.overrides[AXIS] = ((500, json.dumps({"error": "x"})) if state == "failure"
                            else (200, json.dumps(axis)))

    catalog = json.loads(open("locales/%s.json" % locale, encoding="utf-8").read())
    shots = os.environ.get("AXIS_QA_SHOTS")

    for width in WIDTHS:
        gate.visit("/progress-page", width=width)
        gate.page.wait_for_function(
            "() => document.getElementById('ax-card').getAttribute('data-status') !== 'loading'",
            timeout=5000)
        facts = gate.page.evaluate(PROBE)
        cell = (state, locale, width)

        assert not gate.errors, (cell, gate.errors)
        assert not facts["overflow"] and not facts["cardOverflow"], cell
        assert not facts["busy"], cell
        assert not facts["hiddenTakesSpace"], cell
        assert facts["ctaText"] == catalog["progress.axis_review_cta"], cell
        assert facts["ctaHref"] == "/coach?review=progress-insight", cell
        cta = facts["boxes"]["cta"]
        assert cta["height"] >= 40 and cta["width"] > 0, (cell, cta)
        assert cta["right"] <= facts["boxes"]["card"]["right"] + 0.5, cell

        if state == "failure":
            assert facts["status"] == "unavailable", cell
            assert facts["interp"] == catalog["progress.axis_unavailable"], cell
            assert facts["action"] is None and facts["evidence"] == [], cell
            assert facts["meaning"] is None, cell
        else:
            assert facts["status"] in ("available", "insufficient_data"), cell
            assert facts["action"], cell
            assert len(facts["evidence"]) <= 2, cell
            action = facts["boxes"]["action"]
            assert not _overlap(action, cta), (cell, action, cta)
            # Reading order: meaning → (facts) → move → continuation. On wide
            # screens the action/CTA column sits beside the meaning.
            assert facts["boxes"]["interp"]["top"] <= action["top"], cell
            assert action["bottom"] <= cta["top"] + 0.5, cell
            if facts["boxes"]["evidence"]:
                assert facts["boxes"]["interp"]["bottom"] <= \
                    facts["boxes"]["evidence"]["top"] + 0.5, cell
            # Dedup against what the page already says above.
            assert facts["meaning"], cell
            rendered = {facts["interp"], facts["meaning"], facts["action"],
                        *facts["evidence"]}
            assert not rendered & set(facts["current"]), cell
            assert not rendered & set(facts["trends"]), cell
            for text in rendered:
                assert "_" not in text and "{" not in text, (cell, text)

        # The page's reads are exactly the existing ones: one summary, one
        # insight, physique, history — nothing new, nothing repeated.
        reads = [p for p in gate.app_reads() if p.startswith("/api/")]
        assert sorted(reads) == sorted([SUMMARY, AXIS, "/api/progress/physique",
                                        "/api/progress/history"]), (cell, reads)

        if shots:
            os.makedirs(shots, exist_ok=True)
            gate.page.locator("#progress-axis-insight").screenshot(
                path=os.path.join(shots, "%s_%s_%d.png" % (state, locale, width)))
            if width in (390, 1366) and locale == "en":
                gate.page.screenshot(
                    path=os.path.join(shots, "page_%s_%d.png" % (state, width)),
                    full_page=True)
